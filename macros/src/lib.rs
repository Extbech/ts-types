/// Base directory of the project, determined by the `CARGO_MANIFEST_DIR` environment variable.
const BASE_DIR: LazyLock<PathBuf> = LazyLock::new(|| {
    PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("Missing CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .to_path_buf()
});

